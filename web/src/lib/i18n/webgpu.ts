export type WebgpuLocale = 'en' | 'ko' | 'ja';
export type WebgpuMessageKey = keyof typeof messages.en;
export type MessageParams = Record<string, string | number>;
export type MessageSpec = { key: WebgpuMessageKey; params?: MessageParams };
export function webgpuText(locale: WebgpuLocale, key: WebgpuMessageKey, params: MessageParams = {}): string {
  return messages[locale][key].replace(/\{(\w+)\}/g, (placeholder, name: string) => String(params[name] ?? placeholder));
}
export class WebgpuMessageError extends Error {
  constructor(public message_key: WebgpuMessageKey, public message_params: MessageParams = {}, locale: WebgpuLocale = 'ko') {
    super(webgpuText(locale, message_key, message_params));
  }
}
